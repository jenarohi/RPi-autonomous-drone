#!/usr/bin/env python3
"""Generate the Gazebo world (sim/worlds/aerothon_mission.sdf) from sim/course.yaml.

The world is the ORIGINAL SkyScan world from legacy/create_world.py: same models, poses, sizes and colours. Only
differences from the legacy SDF: texture paths are relative to the world file (so the repo is portable) and a fixed
"overview" camera is added for the web UI. tests/test_sim_course.py checks the result against legacy/aerothon_mission.sdf.

    python sim/build_world.py            # rewrites sim/worlds/aerothon_mission.sdf
"""
from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from skyscan.sim.course import Course, CourseObject  # noqa: E402

COURSE_YAML = REPO_ROOT / "sim" / "course.yaml"
WORLD_SDF = REPO_ROOT / "sim" / "worlds" / "aerothon_mission.sdf"


def _n(v: float) -> str:
    """Compact, stable number formatting (3.0 -> '3', 0.011 -> '0.011')."""
    return f"{round(float(v), 6):g}"


def _model(o: CourseObject, course: Course) -> str:
    x, y, z = course.course_to_gz(o.fwd, o.right, o.up)
    sx, sy, sz = o.size
    r, g, b = (_n(c) for c in o.rgb)
    size = f"<size>{_n(sx)} {_n(sy)} {_n(sz)}</size>"
    pose = f"{_n(x)} {_n(y)} {_n(z)} 0 0 0"
    texture = o.extras.get("texture")
    material = f"<ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse>"
    if texture:
        material += f"<pbr><metal><albedo_map>textures/{texture}</albedo_map></metal></pbr>"
    collision = f'<collision name="c"><geometry><box>{size}</box></geometry></collision>' if o.extras.get("collision") else ""
    return (
        f'<model name="{o.id}"><static>true</static><pose>{pose}</pose><link name="l">'
        f'<visual name="v"><geometry><box>{size}</box></geometry><material>{material}</material></visual>'
        f"{collision}</link></model>"
    )


def _overview_camera(cam: dict) -> str:
    if not cam:
        return ""
    px, py, pz, roll, pitch, yaw = (_n(v) for v in cam.get("gz_pose", [4, -9, 8, 0, 0.55, 1.5708]))
    w, h = cam.get("size", [640, 480])
    import math
    hfov = math.radians(float(cam.get("hfov_deg", 75.0)))
    return (
        f'<model name="overview_cam"><static>true</static><pose>{px} {py} {pz} {roll} {pitch} {yaw}</pose>'
        f'<link name="link"><sensor name="overview" type="camera"><camera>'
        f"<horizontal_fov>{_n(hfov)}</horizontal_fov><image><width>{int(w)}</width><height>{int(h)}</height></image>"
        f"<clip><near>0.1</near><far>150</far></clip></camera>"
        f"<always_on>1</always_on><update_rate>{_n(cam.get('update_rate', 10))}</update_rate><visualize>false</visualize>"
        f"</sensor></link></model>"
    )


def build_world(course_file: Path | None = None, out_file: Path | None = None) -> Path:
    course = Course.from_yaml(course_file or COURSE_YAML)
    out = Path(out_file or WORLD_SDF)
    ox, oy, _ = course.origin_gz
    models = "\n".join(_model(o, course) for o in course.objects)
    sdf = f"""<?xml version="1.0" ?>
<!-- GENERATED by sim/build_world.py from sim/course.yaml. Do not edit by hand. Original layout: legacy/create_world.py -->
<sdf version="1.9">
<world name="{course.name}">
<physics name="1ms" type="ignore"><max_step_size>0.001</max_step_size><real_time_factor>1.0</real_time_factor></physics>
<plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
<plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
<plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
<plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>
<plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
<light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 10 0 0 0</pose>
<diffuse>0.8 0.8 0.8 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.5 0.1 -0.9</direction></light>
<model name="ground"><static>true</static><link name="l">
<collision name="c"><geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry></collision>
<visual name="v"><geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
<material><ambient>0.5 0.5 0.5 1</ambient><diffuse>0.5 0.5 0.5 1</diffuse></material></visual></link></model>
<include><uri>model://iris_with_gimbal</uri><name>iris</name><pose>{_n(ox)} {_n(oy)} {_n(course.spawn_z)} 0 0 0</pose></include>
{models}
{_overview_camera(course.overview_camera)}
</world>
</sdf>
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(sdf, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(f"wrote {build_world()}")
